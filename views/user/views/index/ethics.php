<h2 class="wp-block-heading">Our Program</h2>



<p><?= $this->_company['c_name'] ?>’s Ethics &amp; Compliance program is a major focal point and integral part of the company’s culture. It encompasses the key elements of ethics and compliance best practices: tone at the top; policies/procedures; training; and assurance.</p>



<h2 class="wp-block-heading">Training</h2>



<p><?= $this->_company['c_name'] ?>’s mandatory Code of Conduct online training is available in 15 languages. In addition, employees are assigned training on evolving areas of compliance, such as anti-corruption laws, on a regular basis. Short training videos, webinars and in-person training sessions are important means of reaching as many employees as possible. The Ethics and Compliance intranet pages have practical guidance in easy-to-understand summaries, Q&amp;A documents and scenarios on a wide range of topics.</p>



<h2 class="wp-block-heading">Hotline</h2>



<figure class="wp-block-table"><table><tbody><tr><td><?= $this->_company['c_name'] ?> maintains a 24-hour, seven-day-per-week hotline with extensive language capabilities which is open to all <?= $this->_company['c_name'] ?> employees. All calls or emails are thoroughly investigated and brought to closure, and can be made anonymously. <?= $this->_company['c_name'] ?> does not tolerate acts of retaliation against anyone who makes a good faith report of a possible violation, or who participates in an investigation of possible wrongdoing.</td></tr></tbody></table></figure>



<h2 class="wp-block-heading">Governance</h2>



<p><?= $this->_company['c_name'] ?>’s audit program has a broad reach and a risk-based approach, ensuring that regular audits take place and that the results are addressed by management. <?= $this->_company['c_name'] ?>’s executive leadership team communicate regularly and directly about the importance of integrity to all <?= $this->_company['c_name'] ?> employees worldwide. In addition, <?= $this->_company['c_name'] ?> leaders regularly communicate about ethics to their employees. Each geography and business line has an ethics and compliance committee chaired by the head of that business that reports quarterly to the Global Ethics &amp; Compliance Committee regarding relevant issues.</p>
 
