<h2 class="wp-block-heading"><strong>Our nine Life-Preserving Principles</strong></h2>



<p>Our nine Life-Preserving Principles are core to everything we do. </p>



<h3 class="wp-block-heading">1. Demonstrated Management Commitment</h3>



<p>Our Executive, senior and project managers will lead the SH&amp;E improvement process and continuously demonstrate support and commitment.</p>



<h3 class="wp-block-heading">2. Employee Participation</h3>



<p>Our employees will be encouraged and empowered to become actively engaged in our safety processes through their active participation in safety committees, training, audits, observations and inspections. Employees will be encouraged to participate in health initiatives and adopt a healthy lifestyle.</p>



<h3 class="wp-block-heading">3. Budgeting and Staffing for Safety</h3>



<p>Our safety staff will be competent, fully trained and qualified to provide technical resources to our internal and external clients. A budget to support safety activities will be included in project proposals.</p>



<h3 class="wp-block-heading">4. Pre-Planning</h3>



<p>Our design, engineering, project and construction management staffs will deploy effective risk mitigation efforts to design, plan and build safety into every project. Pre-Project and Pre-Task planning will be an effective tool in protecting our employees and the environment.</p>



<h3 class="wp-block-heading">5. Contractor Management</h3>



<p>Our project staff will work closely with our sub-consultants, subcontractors, contractors and JV Partners to provide a safe work environment for employees and members of the public. Our goal of SH&amp;E performance excellence will be equally shared by all project participants.</p>



<h3 class="wp-block-heading">6. Recognition and Rewards</h3>



<p>Our employees will be recognized for their efforts in working safely and their support of our safety efforts.</p>



<h3 class="wp-block-heading">7. Safety Orientation and Training</h3>



<p>Our employees will be provided with effective safety training in order to identify and mitigate hazards in the workplace to prevent injuries to themselves and others who may be affected by their actions.</p>



<h3 class="wp-block-heading">8. Incident Investigation</h3>



<p>Our managers and safety professionals will investigate all recordable incidents and serious near misses to identify contributing factors and root causes in order to prevent a reoccurrence. Lessons learned shall be identified, communicated and implemented.</p>



<h3 class="wp-block-heading">9. Fit for Duty</h3>



<p>Our employees are responsible to report to work each day fit for duty and not to pose a health and safety hazard to themselves or others.</p>
 
